"""R18: extract the pen from Assets/appicon.svg (icon-v2) into a small Avalonia vector (Controls/PenIcon.axaml).
Flattens the SVG transforms into absolute path coordinates, fitted into a 34x26 tile box like the other Tool icons."""
import re, math, numpy as np, sys
SVG=open(sys.argv[1]).read()
def M(a,b,c,d,e,f): return np.array([[a,c,e],[b,d,f],[0,0,1]],float)
def T(x,y): return M(1,0,0,1,x,y)
def R(deg): r=math.radians(deg); return M(math.cos(r),math.sin(r),-math.sin(r),math.cos(r),0,0)
def S(k): return M(k,0,0,k,0,0)
outer=T(440,692)@R(-14.1)@S(0.12023)@R(180)@T(-3980.842,-1628.848)
inner=outer@M(1.140291,1.589552,-1.126476,0.808096,1513.46468,-4225.088765)
g=SVG[SVG.index('<g transform="translate(440'):]
ds=re.findall(r'<path d="([^"]+)" fill="([^"]+)"',g)
paths=[(d,f,inner if i<3 else outer) for i,(d,f) in enumerate(ds)]
def tok(d): return re.findall(r'[MLCZ]|-?[\d.]+',d)
def pts_of(d):
    t=tok(d); out=[];i=0
    while i<len(t):
        if t[i] in 'MLCZ': out.append(t[i]); i+=1
        else: out.append((float(t[i]),float(t[i+1]))); i+=2
    return out
allp=[]
for d,f,A in paths:
    for p in pts_of(d):
        if isinstance(p,tuple): allp.append((A@[p[0],p[1],1])[:2])
P=np.array(allp); lo,hi=P.min(0),P.max(0)
W,H,pad=34,26,1.0
k=min((W-2*pad)/(hi-lo)[0],(H-2*pad)/(hi-lo)[1])
F=T(W/2,H/2)@S(k)@T(-(lo+hi)[0]/2,-(lo+hi)[1]/2)
def xf(A,p): q=(F@A@[p[0],p[1],1])[:2]; return f"{q[0]:.3f},{q[1]:.3f}"
def data(d,A):
    o=[]
    for p in pts_of(d): o.append(p if isinstance(p,str) else xf(A,p))
    return ' '.join(o)
grads={'url(#penA)':((3035.649242,2319.42929),(3342.03896,2318.276722),'#a8a8a8','#3a3a3a'),
       'url(#penB)':((3346.18409,2097.612819),(3163.558659,2099.495636),'#707070','#1e1e1e'),
       'url(#nibT)':((3140,0),(3193,0),'#5a5a5a','#151515')}
out=[]
for i,(d,f,A) in enumerate(paths):
    dd=data(d,A)
    if f in grads:
        a,b,c1,c2=grads[f]
        if f=='url(#nibT)':  # horizontal gradient: evaluate at the nib's own y
            ys=[p[1] for p in pts_of(d) if isinstance(p,tuple)]; y=sum(ys)/len(ys); a=(a[0],y); b=(b[0],y)
        brush=(f'<LinearGradientBrush StartPoint="{xf(A,a)}" EndPoint="{xf(A,b)}" SpreadMethod="Pad">'
               f'<GradientStop Offset="0" Color="{c1}"/><GradientStop Offset="1" Color="{c2}"/></LinearGradientBrush>')
        stroke=' Stroke="{DynamicResource PenIconOutlineBrush}" StrokeThickness="0.45" StrokeJoin="Round"' if f=='url(#penA)' else ''
        out.append(f'    <Path Data="{dd}"{stroke}><Path.Fill>{brush}</Path.Fill></Path>')
    else:
        out.append(f'    <Path Data="{dd}" Fill="#E4E4E4" />')
print(f'''<UserControl xmlns="https://github.com/avaloniaui" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"
             x:Class="OpenTabletArtist.Controls.PenIcon">
  <!-- R18: the pen from the app icon (Assets/appicon.svg, icon-v2): same shape, shading, highlight, nib and
       angle. Generated by tools/make_pen_icon.py into a 34 x 26 box like the other Tool tiles; a thin
       outline (PenIconOutlineBrush) keeps it readable on the dark unselected tile. White capped at #E4E4E4. -->
  <UserControl.Resources>
    <SolidColorBrush x:Key="PenIconOutlineBrush" Color="#8C8C8C" />
  </UserControl.Resources>
  <Viewbox Width="34" Height="26"><Canvas Width="{W}" Height="{H}">
'''+'\n'.join(out)+'''
  </Canvas></Viewbox>
</UserControl>''')
